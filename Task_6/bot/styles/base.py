"""
Абстрактный базовый класс для всех «стилей» генерации эскизов.
Каждый конкретный стиль должен:
  1. Унаследовать этот класс.
  2. Реализовать все абстрактные методы и свойства.
  3. Возвращать при вызове `generate(...)` список путей к сгенерированным файлам (List[str]).
"""

from abc import ABC, abstractmethod
from typing import List, Dict, Any

from aiogram.types import Message


class TattooStyle(ABC):
    """
    Упрощённый базовый класс для всех «стилей» генерации эскизов.
    Единственное обязательное: реализовать метод generate.
    Методы title/description/image_url оставлены как «необязательные»:
    если стиль их не использует, он может не переопределять их.
    """

    def title(self) -> str:
        """
        (Необязательный) Краткое название стиля.
        По умолчанию возвращает пустую строку.
        """
        return ""

    def description(self) -> str:
        """
        (Необязательный) Инструкция/описание стиля.
        По умолчанию — пустая строка.
        """
        return ""

    def image_url(self) -> str:
        """
        (Необязательный) Путь к демо-изображению этого стиля.
        По умолчанию — пустая строка (никакой картинки не будет).
        """
        return ""

    @abstractmethod
    async def generate(self, message: Message, data: Dict[str, Any]) -> List[str]:
        """
        Запускает собственно генерацию эскиза.

        Параметры:
          - message: aiogram.types.Message — чтобы отправлять в чат бот-статусы обработки.
          - data: словарь с обязательными ключами, например {"description_en": "cat"}.

        Возвращает:
          - Список путей к сгенерированным PNG-файлам (List[str]). Если не удалось сгенерировать
            ни одного файла, возвращается пустой список.
        """
        ...

    def get_format_options(self) -> List[Dict[str, Any]]:
        """
        Возвращает список возможных настроек (форматов) генерации.
        Каждый элемент списка — словарь с ключами:
          • "key": уникальная строка-идентификатор,
          • "label": человекочитаемое название.

        Если стиль не поддерживает дополнительных форматов — возвращает пустой список.
        """
        return []

    def update_format(self, data: Dict[str, Any], format_key: str) -> Dict[str, Any]:
        """
        Обновляет переданный словарь `data` в соответствии с выбранным `format_key`.
        Возвращает новый словарь. По умолчанию возвращает `data` без изменений.

        Пример использования:
            if format_key == "JPEG_HIGH":
                data["quality"] = 95
            return data
        """
        return data
